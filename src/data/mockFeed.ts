function build(): FeedItem[] {
  const items: FeedItem[] = [];
  for (const [age, byKind] of Object.entries(SEED) as [AgeGroup, Record<FeedKind, Row[]>][]) {
    for (const kind of ['youtube', 'community'] as const) {
      byKind[kind].forEach((row, i) => {
        const [title, source, gender, views, comments, hoursAgo, emoji, summary, rankDelta, duration] = row;
        items.push({
          id: `${age}-${kind}-${i}`,
          age,
          kind,
          title,
          source,
          gender,
          views,
          comments,
          hoursAgo,
          emoji,
          summary,
          rankDelta,
          duration,
        });
      });
    }
  }
  return items;
}

